"""SageMaker training job used for inference: Qwen3.6-27B, zero-shot, full class distributions.

Standalone (no project imports): it runs in the AWS vLLM container. For every item it scores
each option as the model's answer: the log-probability of the tokens of `<option name><|im_end|>`
after the assistant turn, summed, then a softmax over the options. The end-of-turn token makes an
option that is a prefix of another a complete answer.

How the token log-probabilities are obtained. Two engines compute the same sums:

- vLLM (`method: prompt`): one request per option with prompt log-probabilities. The whole prompt
  is recomputed for every option, which is affordable for two to four options.
- transformers (`engine: transformers`): one forward pass over the prompt, then all option
  suffixes on copies of the cached state. This is the engine the study uses: for this hybrid
  architecture vLLM's prefix cache works in blocks of 784 tokens, so it cannot reuse a prompt
  shorter than that across options (measured on 2026-10-01).
  Before scoring, the engine checks on one item that cached scoring equals full recomputation.

With thinking enabled the reasoning is always generated by vLLM. For a dataset scored by the
transformers engine, the vLLM job saves the reasoning tokens and the transformers job scores the
options after them. With thinking enabled the model first
reasons greedily (at most `max_thinking_tokens`); the options are scored after `</think>`.

Order inside the job: load the model (timed) -> thinking disabled on every item -> single-request
latency sample -> thinking enabled on the subsample. Results are written per dataset to the
checkpoint directory, which SageMaker copies to S3 while the job runs, so a stopped job keeps the
datasets it finished.

Input  (/opt/ml/input/data/prompts):  job.json, <dataset>.jsonl  (id, messages, no label)
       (/opt/ml/input/data/weights):  the staged weights
Output (/opt/ml/checkpoints):         <dataset>.<variant>.jsonl, rendered_examples.json, run.json
"""
import json
import math
import os
import sys
import time
from pathlib import Path

import numpy as np

START = time.time()
END = "<|im_end|>"
THINK_END = "</think>"


def log(msg: str) -> None:
    print(f"qwen: {msg} ({time.time() - START:.0f}s elapsed)", flush=True)


def distribution(sums) -> tuple[list[float], bool]:
    """Softmax over the options' summed log-probabilities; invalid (uniform) if any score is not finite."""
    s = np.asarray(sums, float)
    if len(s) == 0 or not np.all(np.isfinite(s)):
        return [1.0 / max(len(s), 1)] * len(s), False
    p = np.exp(s - s.max())
    return (p / p.sum()).tolist(), True


def option_ids(tok, names: list[str]) -> list[list[int]]:
    return [tok.encode(n + END, add_special_tokens=False) for n in names]


def trie_edges(options: list[list[int]]) -> list[tuple[tuple, int]]:
    """Every distinct (path of option tokens, next token), shortest paths first."""
    edges = {(tuple(o[:t]), o[t]) for o in options for t in range(len(o))}
    return sorted(edges, key=lambda e: (len(e[0]), e))


def common_prefix(seqs: list[list[int]]) -> list[int]:
    """The longest token prefix shared by all sequences."""
    if not seqs:
        return []
    n = min(len(s) for s in seqs)
    for i in range(n):
        if any(s[i] != seqs[0][i] for s in seqs):
            return seqs[0][:i]
    return seqs[0][:n]


def prompt_ids(tok, messages: list[dict], thinking: bool) -> tuple[list[int], str]:
    text = tok.apply_chat_template(messages, tokenize=False, add_generation_prompt=True, enable_thinking=thinking)
    return tok.encode(text, add_special_tokens=False), text


# ---- engines -----------------------------------------------------------------------------------

class VllmEngine:
    name = "vllm"

    def __init__(self, weights: str, job: dict):
        from vllm import LLM
        self.llm = LLM(model=weights, tensor_parallel_size=job["tensor_parallel"], dtype=job["dtype"],
                       max_model_len=job["max_model_len"], gpu_memory_utilization=job["gpu_memory_utilization"],
                       enable_prefix_caching=True, seed=0, limit_mm_per_prompt={"image": 0, "video": 0},
                       disable_log_stats=False)       # logprobs_mode keeps vLLM's default, raw_logprobs
        self.tok = self.llm.get_tokenizer()
        self.requests = 0
        self.method = job.get("vllm_method", "prompt")

    def score(self, prefixes: list[list[int]], options: list[list[int]]) -> np.ndarray:
        if getattr(self, "method", "prompt") == "prompt":
            return self.score_by_prompt_logprobs(prefixes, options)
        return self.score_by_edges(prefixes, options)

    def score_by_edges(self, prefixes: list[list[int]], options: list[list[int]]) -> np.ndarray:
        """Summed raw log-probability of every option after every prefix, one single-token request per trie edge.

        Exact, but only cheaper than prompt log-probabilities when the prefix cache can reuse the prompt."""
        from vllm import SamplingParams, TokensPrompt
        edges = trie_edges(options)

        def ask(pairs):
            reqs = [TokensPrompt(prompt_token_ids=prefixes[i] + list(path)) for i, (path, _) in pairs]
            sps = [SamplingParams(max_tokens=1, temperature=0.0, logprobs=1, allowed_token_ids=[tok], ignore_eos=True)
                   for _, (_, tok) in pairs]
            outs = self.llm.generate(reqs, sps, use_tqdm=False)
            self.requests += len(reqs)
            got = {}
            for (i, (path, tok)), o in zip(pairs, outs):
                c = o.outputs[0]
                if not c.logprobs or tok not in c.logprobs[0]:
                    raise RuntimeError(f"the restricted request did not return the log-probability of token {tok} "
                                       f"(it returned tokens {list(c.token_ids)})")
                got[(i, path, tok)] = c.logprobs[0][tok].logprob
            return got

        lp = ask([(i, edges[0]) for i in range(len(prefixes))])          # one request per item first: it fills the prefix cache
        lp.update(ask([(i, e) for i in range(len(prefixes)) for e in edges[1:]]))
        return np.array([[sum(lp[(i, tuple(o[:t]), o[t])] for t in range(len(o))) for o in options] for i in range(len(prefixes))])

    def score_by_prompt_logprobs(self, prefixes: list[list[int]], options: list[list[int]]) -> np.ndarray:
        """Summed log-probability of every option after every prefix: one request per option, prompt log-probabilities."""
        from vllm import SamplingParams, TokensPrompt
        reqs = [TokensPrompt(prompt_token_ids=p + o) for p in prefixes for o in options]
        outs = self.llm.generate(reqs, SamplingParams(max_tokens=1, temperature=0.0, prompt_logprobs=0), use_tqdm=False)
        self.requests = getattr(self, "requests", 0) + len(reqs)
        out = np.zeros(len(reqs))
        for n, (o, (p, opt)) in enumerate(zip(outs, ((p, o) for p in prefixes for o in options))):
            pl = o.prompt_logprobs
            out[n] = sum(pl[j][tok].logprob for j, tok in zip(range(len(p), len(p) + len(opt)), opt))
        return out.reshape(len(prefixes), len(options))

    def generate(self, prefixes: list[list[int]], max_tokens: int, stop_id: int) -> list[tuple[list[int], bool]]:
        from vllm import SamplingParams, TokensPrompt
        sp = SamplingParams(temperature=0.0, max_tokens=max_tokens, stop_token_ids=[stop_id])
        outs = self.llm.generate([TokensPrompt(prompt_token_ids=p) for p in prefixes], sp, use_tqdm=False)
        return [(list(o.outputs[0].token_ids), o.outputs[0].finish_reason == "length") for o in outs]

    def stats(self) -> dict:
        try:
            got = {m.name: getattr(m, "value", None) for m in self.llm.get_metrics()}
            return {k: v for k, v in got.items() if "prefix_cache" in k or "prompt_tokens" in k}
        except Exception as e:  # noqa: BLE001 - statistics are informative only
            return {"unavailable": f"{type(e).__name__}: {e}"}


class HfEngine:
    """Fallback: one prefill per item, then all option suffixes on copies of the cached state."""
    name = "transformers"

    def __init__(self, weights: str, job: dict, model=None, tok=None):
        import torch
        from transformers import AutoTokenizer
        self.torch = torch
        self.tok = tok or AutoTokenizer.from_pretrained(weights)
        self.model = model or self._load(weights, job)
        self.model.eval()
        self.chunk = int(job.get("option_chunk", 39))             # option sequences per item in one forward pass (77 at once ran out of memory on 22 GB GPUs)
        self.max_items = int(job.get("max_items_per_pass", 64))   # equal-length items in one forward pass
        self.token_budget = int(job.get("token_budget", 8192))    # prompt tokens computed in one forward pass
        self.context_budget = int(job.get("context_budget", 60000))  # option sequences x prefix length held at once
        self.cache_check = None
        self.shared_ids, self.shared_cache = [], None

    def set_shared(self, ids: list[int]) -> None:
        """Compute once the state after a token prefix that every item of a dataset starts with (its
        instructions and option list); items then only run the tokens that follow it."""
        self.shared_ids, self.shared_cache = [], None
        if len(ids) >= 32:
            with self.torch.no_grad():
                out = self.model(input_ids=self.torch.tensor([ids], device=self.model.device), use_cache=True)
            self.shared_ids, self.shared_cache = list(ids), out.past_key_values

    @staticmethod
    def _load(weights: str, job: dict):
        import subprocess
        import torch
        import transformers
        try:
            import accelerate  # noqa: F401 - needed for device_map="auto"
        except ImportError:
            subprocess.run([sys.executable, "-m", "pip", "install", "--quiet", "accelerate"], check=True)
        last = None
        for name in ("AutoModelForImageTextToText", "AutoModelForCausalLM"):
            try:
                return getattr(transformers, name).from_pretrained(weights, dtype=getattr(torch, job["dtype"]), device_map="auto")
            except Exception as e:  # noqa: BLE001 - try the next loader, report the last error
                last = e
        raise RuntimeError(f"transformers could not load the model: {type(last).__name__}: {last}")

    def _expand(self, cache, n: int, batch: int = 1):
        """A copy of the cached state with each of its `batch` sequences repeated `n` times (item-major).

        Every tensor of every cache layer whose first dimension is the batch is repeated: the
        keys and values of full-attention layers, and the convolution and recurrent states of
        linear-attention layers, which have no repeat method of their own in transformers.
        """
        import copy
        torch = self.torch
        c = copy.deepcopy(cache)
        if n == 1:
            return c
        layers = getattr(c, "layers", None)
        if layers is None and batch != 1:
            raise RuntimeError("this cache type cannot be repeated per item")
        if layers is None:
            c.batch_repeat_interleave(n)
            return c

        def rep(v):
            return v.repeat_interleave(n, dim=0) if torch.is_tensor(v) and v.dim() > 0 and v.shape[0] == batch else v

        for layer in layers:
            for name, val in list(vars(layer).items()):
                if isinstance(val, dict):
                    for k in list(val):
                        val[k] = rep(val[k])
                else:
                    setattr(layer, name, rep(val))
        return c

    def check(self, prefix: list[int], options: list[list[int]]) -> dict:
        """Cached scoring against full recomputation on one item; refuses to continue if they differ."""
        torch = self.torch
        opts = options[:3]
        cached = self.score([prefix], opts)[0]
        full = []
        with torch.no_grad():
            for o in opts:
                lp = torch.log_softmax(self.model(input_ids=torch.tensor([prefix + o], device=self.model.device)).logits[0].float(), -1)
                full.append(sum(float(lp[len(prefix) + t - 1, o[t]]) for t in range(len(o))))
        diff = float(np.max(np.abs(cached - np.array(full))))
        self.cache_check = {"options": len(opts), "max_abs_logprob_difference": diff}
        if not np.isfinite(diff) or diff > 0.5:
            raise RuntimeError(f"cached scoring differs from full recomputation by {diff} in log-probability")
        return self.cache_check

    def _states(self, group: list[list[int]]):
        """State after each prefix of a group of equal-length prefixes, and their next-token log-probabilities.

        Prefixes are batched only when they have the same length: padding would pass through the
        recurrent state of the linear-attention layers and change it.
        """
        torch, n, b = self.torch, len(self.shared_ids), len(group)
        if self.shared_cache is not None and len(group[0]) > n and all(p[:n] == self.shared_ids for p in group):
            t = torch.tensor([p[n:] for p in group], device=self.model.device)
            mask = torch.ones((b, len(group[0])), dtype=torch.long, device=self.model.device)
            out = self.model(input_ids=t, past_key_values=self._expand(self.shared_cache, b), attention_mask=mask, use_cache=True)
        else:
            out = self.model(input_ids=torch.tensor(group, device=self.model.device), use_cache=True)
        return out.past_key_values, torch.log_softmax(out.logits[:, -1].float(), -1)

    def score(self, prefixes: list[list[int]], options: list[list[int]]) -> np.ndarray:
        torch = self.torch
        res = np.zeros((len(prefixes), len(options)))
        by_len: dict[int, list[int]] = {}
        for i, p in enumerate(prefixes):
            by_len.setdefault(len(p), []).append(i)
        width_all = max(len(o) for o in options)
        with torch.no_grad():
            for length, idx in by_len.items():
                rest = max(length - len(self.shared_ids), 1) if self.shared_cache is not None else length
                step = max(1, min(self.max_items, self.token_budget // rest, self.context_budget // (length * min(len(options), self.chunk))))
                for s0 in range(0, len(idx), step):
                    part = idx[s0: s0 + step]
                    b = len(part)
                    cache, first = self._states([prefixes[i] for i in part])
                    per = max(1, min(self.chunk, self.context_budget // (length * b)))
                    for s in range(0, len(options), per):
                        opts = options[s: s + per]
                        n, width = len(opts), max(len(o) for o in opts)
                        c = self._expand(cache, n, batch=b)                   # item-major: item 0's options, item 1's, ...
                        ids = torch.full((b * n, width), self.tok.pad_token_id or 0, dtype=torch.long, device=self.model.device)
                        for j, o in enumerate(opts):
                            ids[j::n, : len(o)] = torch.tensor(o, device=self.model.device)
                        mask = torch.ones((b * n, length + width), dtype=torch.long, device=self.model.device)
                        logits = self.model(input_ids=ids, past_key_values=c, attention_mask=mask, use_cache=True).logits.float()
                        # log-probability of each option's own next token at every position: target logit minus log-sum-exp
                        target = torch.zeros((b * n, width), dtype=torch.long, device=logits.device)
                        for j, o in enumerate(opts):
                            if len(o) > 1:
                                target[j::n, : len(o) - 1] = torch.tensor(o[1:], device=logits.device)
                        lp = (logits.gather(-1, target.unsqueeze(-1)).squeeze(-1) - torch.logsumexp(logits, -1)).cpu().numpy()
                        f = first.cpu().numpy()
                        for k, i in enumerate(part):
                            for j, o in enumerate(opts):
                                res[i, s + j] = f[k, o[0]] + lp[k * n + j, : len(o) - 1].sum()   # first token from the prefix's last position
                        del c, logits, lp
        del width_all
        return res

    def generate(self, prefixes, max_tokens, stop_id):
        torch, out = self.torch, []
        with torch.no_grad():
            for p in prefixes:
                g = self.model.generate(torch.tensor([p], device=self.model.device), max_new_tokens=max_tokens,
                                        do_sample=False, eos_token_id=stop_id)
                new = g[0, len(p):].tolist()
                out.append((new, stop_id not in new and len(new) >= max_tokens))
        return out

    def stats(self) -> dict:
        return {"engine": "transformers, prompt state reused for every option", "cache_check": self.cache_check}


# ---- the job -----------------------------------------------------------------------------------

def read_jsonl(path: Path) -> list[dict]:
    with open(path) as f:
        return [json.loads(x) for x in f if x.strip()]


def write_jsonl(path: Path, rows: list[dict]) -> None:
    tmp = path.with_suffix(".tmp")
    with open(tmp, "w") as f:
        for r in rows:
            f.write(json.dumps(r) + "\n")
    os.replace(tmp, path)


def score_items(engine, items: list[dict], opts: list[list[int]], thinking, job: dict) -> list[dict]:
    """Class distributions for `items`.

    thinking: False (disabled); "score" (reason, then score); "generate" (reason and save the reasoning
    tokens, no scoring: another job scores them); "given" (score after the reasoning tokens the items carry).
    """
    tok, rows = engine.tok, []
    chunk = int(job.get("think_items_per_call", 128) if thinking in ("score", "generate") else job.get("items_per_call", 16))
    think_end = tok.convert_tokens_to_ids(THINK_END)
    sep = tok.encode("\n\n", add_special_tokens=False)
    for s in range(0, len(items), chunk):
        part = items[s: s + chunk]
        prefixes = [prompt_ids(tok, it["messages"], bool(thinking))[0] for it in part]
        extra = [{} for _ in part]
        t = time.time()
        if thinking in ("score", "generate"):
            gens = engine.generate(prefixes, job["max_thinking_tokens"], think_end)
            for n, (ids, truncated) in enumerate(gens):
                if not ids or ids[-1] != think_end:
                    ids = ids + [think_end]
                extra[n] = {"thinking_tokens": len(ids), "thinking_truncated": bool(truncated), "reasoning_ids": ids}
        elif thinking == "given":
            extra = [{"thinking_tokens": len(it["reasoning_ids"]), "thinking_truncated": bool(it["thinking_truncated"]),
                      "reasoning_ids": it["reasoning_ids"], "generation_seconds": it.get("seconds")} for it in part]
        if thinking:
            prefixes = [p + ex["reasoning_ids"] + sep for p, ex in zip(prefixes, extra)]
        if thinking == "generate":
            secs = (time.time() - t) / len(part)
            rows += [{"id": it["id"], "seconds": secs, **ex} for it, ex in zip(part, extra)]
            continue
        try:
            sums = engine.score(prefixes, opts)
            failed = None
        except Exception as e:  # noqa: BLE001 - a failed chunk is recorded as invalid items, not hidden
            sums, failed = np.full((len(part), len(opts)), np.nan), f"{type(e).__name__}: {e}"
        secs = (time.time() - t) / len(part)
        for it, p, sc, ex in zip(part, prefixes, sums, extra):
            probs, valid = distribution(sc)
            ex = {k: v for k, v in ex.items() if k != "reasoning_ids"}
            rows.append({"id": it["id"], "valid": valid, "p": probs, "prompt_tokens": len(p), "seconds": secs,
                         **({"failure": failed} if failed else {}), **ex})
    return rows


def main(prompts: Path, weights: str, out: Path, engine=None) -> dict:
    job = json.loads((prompts / "job.json").read_text())
    out.mkdir(parents=True, exist_ok=True)
    t = time.time()
    engine = engine or (VllmEngine(weights, job) if job.get("engine", "vllm") == "vllm" else HfEngine(weights, job))
    if "items_per_call" not in job and engine.name == "transformers":
        job["items_per_call"] = 256              # the engine batches equal-length items within a call
    load_s = time.time() - t
    log(f"model loaded with {engine.name} in {load_s:.0f}s")
    run = {"engine": engine.name, "load_s": load_s, "datasets": {}, "rendered_examples": {}}
    rendered = {}
    for ds in job["datasets"]:
        items = {it["id"]: it for it in read_jsonl(prompts / f"{ds}.jsonl")}
        names = job["options"][ds]
        opts = option_ids(engine.tok, names)
        info = {"options": names, "option_tokens": [len(o) for o in opts]}
        ex = items[job["example_id"][ds]]
        rendered[ds] = {"id": ex["id"], "thinking_disabled": prompt_ids(engine.tok, ex["messages"], False)[1]}
        if hasattr(engine, "set_shared"):          # the instructions and option list are the same for every item
            some = [prompt_ids(engine.tok, it["messages"], False)[0] for it in list(items.values())[:16]]
            engine.set_shared(common_prefix(some)[:-1])
            info["shared_prefix_tokens"] = len(engine.shared_ids)
        if hasattr(engine, "check"):
            info["cache_check"] = engine.check(prompt_ids(engine.tok, ex["messages"], False)[0], opts)
            log(f"{ds}: shared prefix {len(engine.shared_ids)} tokens; cache check: {info['cache_check']}")
        think_mode = (job.get("think_mode") or {}).get(ds, "score")
        for variant, thinking in (("nothink", False), ("think", think_mode)):
            ids = job["sets"][ds][variant]
            if not ids:
                continue
            t = time.time()
            rows = score_items(engine, [items[i] for i in ids], opts, thinking, job)
            info[variant] = {"items": len(rows), "seconds": time.time() - t, "mode": thinking or "disabled",
                             "prompt_tokens": int(sum(r.get("prompt_tokens", 0) for r in rows)),
                             "invalid": int(sum(not r.get("valid", True) for r in rows))}
            write_jsonl(out / (f"{ds}.think_reasoning.jsonl" if thinking == "generate" else f"{ds}.{variant}.jsonl"), rows)
            log(f"{ds}: {variant} ({info[variant]['mode']}): {len(rows)} items in {info[variant]['seconds']:.0f}s")
            if variant == "nothink" and getattr(engine, "method", None) == "edges" and job.get("cross_check_items"):
                part = [items[i] for i in ids[: job["cross_check_items"]]]
                pre = [prompt_ids(engine.tok, it["messages"], False)[0] for it in part]
                a, b = engine.score(pre, opts), engine.score_by_prompt_logprobs(pre, opts)
                info["cross_check"] = {"items": len(part), "max_abs_logprob_difference": float(np.max(np.abs(a - b))),
                                       "max_abs_probability_difference": float(max(
                                           np.max(np.abs(np.array(distribution(x)[0]) - np.array(distribution(y)[0])))
                                           for x, y in zip(a, b)))}
                log(f"{ds}: cross-check on {len(part)} items: {info['cross_check']}")
            if variant == "nothink":                 # the single-request latency sample, after the batch run
                lat = []
                for i in job["sets"][ds]["latency"]:
                    t1 = time.time()
                    score_items(engine, [items[i]], opts, False, {**job, "items_per_call": 1})
                    lat.append(time.time() - t1)
                info["latency_s"] = lat
        run["datasets"][ds] = info
        (out / "rendered_examples.json").write_text(json.dumps(rendered, indent=1))
        (out / "run.json").write_text(json.dumps({**run, "elapsed_s": time.time() - START}, indent=1))
    run["cache_stats"] = engine.stats()
    run["requests"] = getattr(engine, "requests", None)
    run["scoring"] = ("one request per option, prompt log-probabilities" if engine.name == "vllm" and getattr(engine, "method", "") == "prompt"
                      else "one single-token request per trie edge" if engine.name == "vllm"
                      else "one forward pass over the prompt, option suffixes on copies of the cached state")
    try:
        import torch
        import transformers
        run["versions"] = {"torch": torch.__version__, "transformers": transformers.__version__, "python": sys.version.split()[0]}
        if engine.name == "vllm":
            import vllm
            run["versions"]["vllm"] = vllm.__version__
        run["gpus"] = [torch.cuda.get_device_name(i) for i in range(torch.cuda.device_count())]
    except Exception:  # noqa: BLE001
        pass
    run["elapsed_s"] = time.time() - START
    (out / "run.json").write_text(json.dumps(run, indent=1))
    log("done")
    return run


