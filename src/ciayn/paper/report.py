def build(mode: str, incomplete: list[str]) -> str:
    gen = config.PAPER / "generated"
    built = json.loads((gen / "mode.json").read_text())
    if built["mode"] != mode:
        raise RuntimeError(f"paper/generated was built in {built['mode']} mode; run `python -m ciayn paper --mode {mode}` first")
    values = {k: plain(v["value"]) for k, v in json.loads((gen / "macro_sources.json").read_text()).items()}
    baseline = re.sub(r"\\textbf\{(.*?)\}", r"\1", (gen / "text_baseline.tex").read_text(), flags=re.S)
    baseline = re.sub(r"\(Figure~\\ref\{[^}]*\}\)", "(in the paper)", baseline)
    baseline = plain(" ".join(baseline.split()))
    from datetime import datetime, timezone

    check = config.RESULTS / mode / "paper_check.json"
    fmt = (json.loads(check.read_text()).get("format") or {}).get("page_limit") if check.exists() else None
    values.update(MainTextEndPage=fmt["main_text_ends_on_page"] if fmt else "not checked",
                  PageLimit=config.load("submission")["page_limit"])
    values.update(mode=mode, CheckedAt=datetime.now(timezone.utc).strftime("%Y-%m-%d"), BaselineText=baseline,
                  MockNote="\n**These are MOCK results from synthetic predictors, not findings.**\n" if built["mockdraft"] else "",
                  Incomplete="\n".join(f"- {line}" for line in incomplete))
    missing = sorted(set(re.findall(r"\{(\w+)\}", TEMPLATE)) - set(values))
    if missing:
        raise RuntimeError(f"report: no saved value for {', '.join(missing)}; nothing is written")
    return TEMPLATE.format(**values)


def incomplete_items(mode: str) -> list[str]:
    path = config.CONFIGS / "report_notes.yaml"
    notes = list(config.load("report_notes").get("incomplete", [])) if path.exists() else []
    gen = json.loads((config.PAPER / "generated" / "macro_sources.json").read_text())
    if int(gen["BaselinesMissing"]["value"]) > 0:
        notes.insert(0, f"The XGBoost baseline is missing for {gen['BaselinesMissing']['value']} dataset(s): their SageMaker runs "
                        "had not completed when the paper was built. The paper marks those rows as not available.")
    return notes


def run(args) -> int:
    text = build(args.mode, incomplete_items(args.mode))
    out = config.DOCS / ("REPORT.md" if args.mode == "live" else "REPORT.mock.md")
    out.write_text(text)
    print(f"report ({args.mode}): wrote {out}")
    return 0
