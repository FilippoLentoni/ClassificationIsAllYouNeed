"""Dataset documentation generated from the experiment configuration (one file per dataset)."""
from __future__ import annotations

import numpy as np

from .. import config
from . import manifest
from .datasets import Dataset
from .serialize import MISSING_NOTE, MISSING_VALUE


def _source(ds: Dataset) -> str:
    s = ds.source
    if "openml" in s:
        return f"OpenML dataset {s['openml']} (`{s['name']}`, version {s['version']})"
    if "sklearn" in s:
        import sklearn

        return f"scikit-learn {sklearn.__version__} `sklearn.datasets.{s['sklearn']}` ({s['origin']})"
    if "hf" in s:
        cfg = f", configuration `{s['config']}`" if s.get("config") else ""
        return f"Hugging Face `{s['hf']}`{cfg}, revision `{s['revision']}`"
    raise ValueError(f"unknown source for {ds.name}")


def card(ds: Dataset) -> str:
    cfg_all = config.load("datasets")
    cfg = cfg_all[ds.name]
    from ..backends.jev import instructions

    counts = np.bincount(ds.labels(ds.eval_ids), minlength=len(ds.classes))
    lines = [f"# {ds.title} (`{ds.name}`)", "",
             "Generated by `python -m ciayn freeze` from `configs/datasets.yaml`. Do not edit by hand.", "",
             f"- **Source and version:** {_source(ds)}",
             f"- **Task type:** {ds.kind}, {len(ds.classes)} classes",
             f"- **Positive class:** {ds.positive if ds.positive else 'not applicable (multiclass)'}",
             f"- **Identifiers frozen:** {manifest.frozen_at()} "
             f"(sha256 of `results/splits/{ds.name}.json`: `{manifest.read_manifest()[ds.name + '.json']}`)"]
    if ds.protocol == "repeated":
        r0 = ds.repeats[0]
        lines += [f"- **Split protocol:** {len(ds.repeats)} repeated stratified splits over all {len(ds.frame)} rows, "
                  f"seeds 0 to {len(ds.repeats) - 1}; each repeat has train {len(r0['train'])}, "
                  f"validation {len(r0['val'])}, test {len(r0['test'])}",
                  f"- **Evaluation examples:** {len(ds.eval_ids)} distinct rows are a test row in at least one "
                  f"repeat; Jev predicts all {len(ds.jev_ids)} rows once, because each repeat's validation and "
                  "test parts both use its predictions"]
    else:
        r0 = ds.repeats[0]
        lines += [f"- **Split protocol:** official held-out split `{cfg['eval_split']}` ({len(r0['test'])} examples, "
                  f"all used); validation {len(r0['val'])} examples drawn stratified from the official training "
                  f"split with seed {cfg_all['seed']}; training {len(r0['train'])} examples (the rest of it)",
                  f"- **Jev validation items:** {len(ds.jev_val)} (the first items of the validation draw, "
                  "used only to select Jev's decision threshold)" if ds.jev_val else
                  "- **Jev validation items:** none (no threshold selection for this dataset)"]
    lines += ["", "## Preprocessing and serialization", ""]
    if ds.kind == "tabular":
        n_missing = int(ds.frame.isna().sum().sum())
        lines += [f"- One line per feature, `name: value`, in a fixed feature order ({len(ds.features)} features).",
                  "- Categorical codes are decoded to readable labels; whole-number values are written without decimals.",
                  f"- **Missing values** are written as `{MISSING_VALUE}`; this dataset has {n_missing} missing values.",
                  f"- A masked feature (explanations) is removed from the input; the instructions end with "
                  f"\"{MISSING_NOTE}\"",
                  "- The gold label is never part of the input."]
    else:
        lines += [f"- The text is the input, with {cfg_all['text_normalisation']}.",
                  "- **Missing values:** not applicable; no example has an empty text."
                  if (ds.frame["text"].str.len() > 0).all() else "- **Missing values:** some texts are empty.",
                  "- A masked word (explanations) is removed from the text.",
                  "- The gold label is never part of the input."]
    lines += ["", "## Question sent to Jev", "", f"- **Instructions:** \"{instructions(ds)}\"",
              "- **Options and descriptions, in the order sent:**", "",
              "| # | Class | Description | Evaluation examples |", "|---|---|---|---|"]
    lines += [f"| {i} | `{c}` | {ds.criteria[c]} | {counts[i]} |" for i, c in enumerate(ds.classes)]
    return "\n".join(lines) + "\n"


def write_cards(dss: list[Dataset]) -> list[str]:
    out = config.DOCS / "datasets"
    out.mkdir(parents=True, exist_ok=True)
    paths = []
    for ds in dss:
        (out / f"{ds.name}.md").write_text(card(ds))
        paths.append(str(out / f"{ds.name}.md"))
    return paths


def run_freeze(args) -> int:
    from . import datasets

    dss = [datasets.build(n) for n in config.DATASETS]
    digests = manifest.freeze(dss, overwrite=getattr(args, "refreeze", False))
    datasets.clear_cache()
    paths = write_cards(dss)
    for ds in dss:
        r0 = ds.repeats[0]
        print(f"freeze: {ds.name:<10} {ds.protocol:<8} repeats {len(ds.repeats):>2}  "
              f"train {len(r0['train']):>6} val {len(r0['val']):>5} test {len(r0['test']):>5}  "
              f"evaluation {len(ds.eval_ids):>5}  jev {len(ds.jev_ids):>5}  {digests[ds.name + '.json'][:12]}")
    print(f"freeze: manifest {config.SPLITS / manifest.MANIFEST}; {len(paths)} dataset documents in {config.DOCS / 'datasets'}")
    return 0
